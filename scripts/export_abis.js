const fs = require('fs');
const path = require('path');

const contractsDir = path.join(__dirname, '..', 'artifacts', 'contracts');
const targetDir = path.join(__dirname, '..', 'frontend', 'src', 'contracts');

if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

function getAbi(contractPath, artifactName) {
  const fullPath = path.join(contractsDir, contractPath, `${artifactName}.json`);
  const data = JSON.parse(fs.readFileSync(fullPath, 'utf8'));
  return data.abi;
}

const abis = {
  ClaimManager: getAbi('ClaimManager.sol', 'ClaimManager'),
  AccessRegistry: getAbi('AccessRegistry.sol', 'AccessRegistry'),
  HospitalRegistry: getAbi('HospitalRegistry.sol', 'HospitalRegistry'),
  AuditAnchor: getAbi('AuditAnchor.sol', 'AuditAnchor'),
  Groth16Verifier: getAbi('Verifier.sol', 'Groth16Verifier'),
};

const deployedAddresses = JSON.parse(
  fs.readFileSync(path.join(__dirname, '..', 'deployed_addresses.json'), 'utf8')
);

const outContent = `// Auto-generated by scripts/export_abis.js
export const DEPLOYED_ADDRESSES = ${JSON.stringify(deployedAddresses, null, 2)};

export const SEPOLIA_CONFIG = {
  chainId: 11155111,
  chainIdHex: '0xaa36a7',
  chainName: 'Sepolia Testnet',
  nativeCurrency: { name: 'Sepolia Ether', symbol: 'SEP', decimals: 18 },
  rpcUrls: ['https://rpc.sepolia.org', 'https://ethereum-sepolia-rpc.publicnode.com'],
  blockExplorerUrls: ['https://sepolia.etherscan.io'],
};

export const CONTRACT_ABIS = ${JSON.stringify(abis, null, 2)};
`;

fs.writeFileSync(path.join(targetDir, 'index.js'), outContent, 'utf8');
console.log('✅ Successfully exported ABIs and configuration to frontend/src/contracts/index.js');
